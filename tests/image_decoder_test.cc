#include <cstdint>
#include <filesystem>
#include <fstream>
#include <iostream>

#include "resources/image_decoder.h"

int main()
{
	static constexpr uint8_t png[] = {
		0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00,
		0x00, 0x0d, 0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x02,
		0x00, 0x00, 0x00, 0x02, 0x08, 0x06, 0x00, 0x00, 0x00, 0x72,
		0xb6, 0x0d, 0x24, 0x00, 0x00, 0x00, 0x09, 0x70, 0x48, 0x59,
		0x73, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x00,
		0x4f, 0x25, 0xc4, 0xd6, 0x00, 0x00, 0x00, 0x15, 0x49, 0x44,
		0x41, 0x54, 0x78, 0x9c, 0x63, 0xd0, 0xd5, 0xfb, 0xff, 0x1f,
		0x84, 0x19, 0x18, 0x18, 0xfe, 0xfe, 0x07, 0x61, 0x00, 0x4a,
		0x10, 0x08, 0xab, 0x61, 0x1e, 0x2c, 0xe9, 0x00, 0x00, 0x00,
		0x00, 0x49, 0x45, 0x4e, 0x44, 0xae, 0x42, 0x60, 0x82
	};
	const auto path = std::filesystem::temp_directory_path() /
			  "declgl-image-decoder-orientation.png";
	{
		std::ofstream stream(path, std::ios::binary | std::ios::trunc);
		stream.write(reinterpret_cast<const char *>(png), sizeof(png));
		if (!stream) {
			std::cerr << "failed to write orientation fixture\n";
			return 1;
		}
	}

	auto natural = declgl::decode_image_file(path.string(), {});
	auto flipped =
		declgl::decode_image_file(path.string(), {}, true);
	std::error_code remove_error;
	std::filesystem::remove(path, remove_error);
	if (!natural.ok() || !flipped.ok() || natural.width != 2 ||
	    natural.height != 2 || flipped.width != natural.width ||
	    flipped.height != natural.height) {
		std::cerr << "failed to decode orientation fixture\n";
		return 1;
	}

	constexpr int row_bytes = 2 * 4;
	for (int column = 0; column < row_bytes; ++column) {
		if (flipped.pixels[column] != natural.pixels[row_bytes + column] ||
		    flipped.pixels[row_bytes + column] != natural.pixels[column]) {
			std::cerr << "flip_y did not reverse decoded rows\n";
			return 1;
		}
	}
	return 0;
}
